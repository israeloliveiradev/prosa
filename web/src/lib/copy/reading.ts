export type ReadingCopy = (typeof READING)["pt"];

const CEFR = ["A1", "A2", "B1", "B2", "C1", "C2"] as const;
export type NewsLevel = (typeof CEFR)[number];

export interface NewsBand {
  id: NewsLevel;
  relation: "easier" | "yours" | "harder";
}

function asLevel(level: string | null | undefined): NewsLevel {
  return CEFR.includes(level as NewsLevel) ? (level as NewsLevel) : "A2";
}

/** As faixas de texto oferecidas: uma abaixo, a do aluno e uma acima (quando existem). */
export function newsBandsFor(level: string | null | undefined): NewsBand[] {
  const own = asLevel(level);
  const index = CEFR.indexOf(own);
  const bands: NewsBand[] = [];
  if (index > 0) {
    bands.push({ id: CEFR[index - 1], relation: "easier" });
  }
  bands.push({ id: own, relation: "yours" });
  if (index < CEFR.length - 1) {
    bands.push({ id: CEFR[index + 1], relation: "harder" });
  }
  return bands;
}

/** Faixa inicial: o nível da conta (ou A2 quando a conta não tem nível válido). */
export function defaultNewsLevel(level: string | null | undefined): NewsLevel {
  return asLevel(level);
}

export function isNewsTheme(value: string): value is NewsTheme {
  return (NEWS_THEMES as readonly string[]).includes(value);
}

/**
 * Temas oferecidos: os do perfil primeiro (inclusive os livres, digitados pela pessoa),
 * depois os 8 temas canônicos que faltam. Sem duplicatas nem vazios.
 */
export function newsThemeList(interests: ReadonlyArray<string> | null | undefined): string[] {
  const seen = new Set<string>();
  const list: string[] = [];
  for (const raw of [...(interests ?? []), ...NEWS_THEMES]) {
    const item = raw.trim().slice(0, 80);
    const key = item.toLowerCase();
    if (item.length < 2 || seen.has(key)) {
      continue;
    }
    seen.add(key);
    list.push(item);
  }
  return list;
}

/** Rótulo de um tema no idioma da interface; temas livres aparecem como foram digitados. */
export function themeLabel(theme: string, copy: Pick<ReadingCopy, "themes">): string {
  return isNewsTheme(theme) ? copy.themes[theme] : theme;
}
