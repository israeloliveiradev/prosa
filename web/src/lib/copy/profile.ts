export type ProfileCopy = (typeof PROFILE)["pt"];

export function mindName(id: string, copy: Pick<ProfileCopy, "minds">): string {
  return copy.minds[id as MindId]?.name ?? id;
}

export function mindLine(id: string, copy: Pick<ProfileCopy, "minds">): string {
  return copy.minds[id as MindId]?.line ?? "";
}

/** O backend (até o M2) só guarda pt ou en como idioma de interface da conta. */
export function accountLocale(locale: DisplayLocale): "pt" | "en" | null {
  return locale === "pt" || locale === "en" ? locale : null;
}

/** Faixa CEFR estimada da escuta a partir do índice 0–100 do servidor (mesma régua de CompetenceLine). */
export function listeningBand(listening: number): string {
  if (listening >= 75) {
    return "B2";
  }
  if (listening >= 55) {
    return "B1";
  }
  if (listening >= 40) {
    return "A2";
  }
  if (listening > 0) {
    return "A1";
  }
  return "";
}

/** Cursos com o ativo primeiro; os outros na ordem do servidor. Sem duplicatas de idioma. */
export function orderTracks<T extends { target_lang: string; active?: boolean }>(tracks: readonly T[], currentTarget: string): T[] {
  const seen = new Set<string>();
  const unique = tracks.filter((track) => {
    if (seen.has(track.target_lang)) {
      return false;
    }
    seen.add(track.target_lang);
    return true;
  });
  const isCurrent = (track: T) => track.target_lang === currentTarget;
  return [...unique.filter(isCurrent), ...unique.filter((track) => !isCurrent(track))];
}

/** Ofensiva no singular ou plural. */
export function streakText(count: number, copy: Pick<ProfileCopy, "streakOne" | "streakMany">): string {
  return (count === 1 ? copy.streakOne : copy.streakMany).replace("{n}", String(count));
}
