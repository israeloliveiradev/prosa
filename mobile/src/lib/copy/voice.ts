export type VoiceCopy = (typeof VOICE_COPY)["pt"];

/** Textos da voz no idioma de interface atual (fora de componentes React). */
export function voiceCopy(): VoiceCopy {
  return areaCopy(VOICE_COPY, getLocale());
}

/** Troca `{chave}` pelos valores. */
export function fillCopy(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match));
}
